function normalizeLocale(value: string | null | undefined): Locale | null {
  const locale = value?.toLowerCase().split("-")[0];
  return localeOptions.some((option) => option.value === locale) ? (locale as Locale) : null;
}

function detectLocale(): Locale {
  try {
    const stored = normalizeLocale(window.localStorage.getItem(storageKey));
    if (stored) return stored;
  } catch {
    // Ignore unavailable browser storage.
  }
  if (typeof navigator !== "undefined") {
    for (const language of navigator.languages ?? [navigator.language]) {
      const detected = normalizeLocale(language);
      if (detected) return detected;
    }
  }
  return "en";
}

let activeLocale: Locale = typeof window === "undefined" ? "en" : detectLocale();

export function getLocale(): Locale {
  return activeLocale;
}

export function setLocale(locale: Locale): void {
  activeLocale = locale;
  if (typeof window === "undefined") return;
  try {
    window.localStorage.setItem(storageKey, locale);
  } catch {
    // Ignore unavailable browser storage.
  }
}

export function t(message: string, values: Record<string, string | number> = {}): string {
  const translated = activeLocale === "en" ? message : translations[activeLocale][message] ?? message;
  return translated.replace(/\{(\w+)\}/g, (match, key: string) => String(values[key] ?? match));
}

export function localizeElement(root: ParentNode): void {
  if (typeof document === "undefined") return;
  document.documentElement.lang = activeLocale;
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  const textNodes: Text[] = [];
  while (walker.nextNode()) textNodes.push(walker.currentNode as Text);
  for (const node of textNodes) {
    if (node.parentElement?.closest("code, pre, script, style")) continue;
    const source = node.data.trim();
    if (!source) continue;
    const translated = t(source);
    if (translated !== source) node.data = node.data.replace(source, translated);
  }
  for (const element of root.querySelectorAll<HTMLElement>("[aria-label], [placeholder], [title]")) {
    for (const attribute of ["aria-label", "placeholder", "title"] as const) {
      const value = element.getAttribute(attribute);
      if (value) element.setAttribute(attribute, t(value));
    }
  }
}
